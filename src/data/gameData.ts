// Helper calculations
export function getFoodUpgradeCost(foodLevel: number): number {
  return Math.round(12 * Math.pow(1.35, foodLevel - 1));
}

export function getBaseUpgradeCost(baseLevel: number): number {
  return Math.round(15 * Math.pow(1.35, baseLevel - 1));
}

export function getBaseFoodRate(foodLevel: number): number {
  return 1.0 + (foodLevel - 1) * 0.09;
}

export function getAgeDef(ageId: AgeId): AgeDef {
  return AGES.find((a) => a.id === ageId) || AGES[0];
}

export function getAgeByIndex(index: number): AgeDef {
  const safeIndex = Math.max(0, Math.min(AGES.length - 1, index));
  return AGES[safeIndex];
}

export function getAgeIndex(ageId: AgeId): number {
  return AGES.findIndex((a) => a.id === ageId);
}
