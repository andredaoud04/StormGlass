/**
 * Builds every runtime image into public/assets, writes public/assets/manifest.json and one spec
 * per asset in docs/art-specs/. Run with `npm run art`. Output is deterministic.
 */
import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import type { AnimEntry, AssetEntry, Manifest } from '../../src/engine/manifest';
import { A, B, G, Img, R } from './img';
import { INK, TEAM_BLUE, TEAM_RED, MOSS, GOLD, WOOD, STONE } from './palette';
import { packSheet } from './rig';
import { STONE_TROOPS } from './troops/catalog';
import { stoneEnv } from './env/stone';
import { BASE_FRONT, BASE_GROUND, flagFrames, stoneFortress } from './bases/stone';
import { bigFont, smallFont } from './ui/font';
import { icons } from './ui/icons';
import * as ui from './ui/ui';
import * as fx from './fx';

const ROOT = join(import.meta.dirname, '../..');
const OUT = join(ROOT, 'public/assets');
const SPECS = join(ROOT, 'docs/art-specs');

interface Spec {
  key: string;
  entry: AssetEntry;
  desc: string;
  colors: string[];
}

class Registry {
  manifest: Manifest = { version: 1, assets: {}, sounds: {}, meta: {} };
  specs: Spec[] = [];

  private save(file: string, img: Img): string[] {
    img.save(join(OUT, file));
    const set = new Set<string>();
    for (const c of img.data) if (A(c)) set.add('#' + [R(c), G(c), B(c)].map((v) => v.toString(16).padStart(2, '0')).join(''));
    return [...set];
  }

  image(key: string, file: string, img: Img, desc: string, opts: { anchor?: [number, number]; slice?: [number, number, number, number] } = {}): void {
    const colors = this.save(file, img);
    const entry: AssetEntry = { kind: 'image', file, w: img.w, h: img.h, ...opts };
    this.manifest.assets[key] = entry;
    this.specs.push({ key, entry, desc, colors });
  }

  sheet(key: string, file: string, img: Img, frameW: number, frameH: number, anchor: [number, number], anims: Record<string, AnimEntry>, desc: string, muzzle?: [number, number]): void {
    const colors = this.save(file, img);
    const entry: AssetEntry = { kind: 'sheet', file, frameW, frameH, anchor, anims, ...(muzzle ? { muzzle } : {}) };
    this.manifest.assets[key] = entry;
    this.specs.push({ key, entry, desc, colors });
  }

  strip(key: string, file: string, s: fx.Strip): void {
    const fw = Math.max(...s.frames.map((f) => f.w));
    const fh = Math.max(...s.frames.map((f) => f.h));
    const img = new Img(fw * s.frames.length, fh);
    s.frames.forEach((f, i) => img.blit(f, i * fw, 0));
    const colors = this.save(file, img);
    const entry: AssetEntry = { kind: 'strip', file, frameW: fw, frameH: fh, frames: s.frames.length, fps: s.fps, anchor: s.anchor };
    this.manifest.assets[key] = entry;
    this.specs.push({ key, entry, desc: s.desc, colors });
  }

  font(key: string, file: string, f: ReturnType<typeof smallFont>, desc: string): void {
    const colors = this.save(file, f.img);
    const entry: AssetEntry = { kind: 'font', file, cellW: f.cellW, cellH: f.cellH, glyphs: f.glyphs, widths: f.widths, spacing: 1 };
    this.manifest.assets[key] = entry;
    this.specs.push({ key, entry, desc, colors });
  }

  writeAll(): void {
    writeFileSync(join(OUT, 'manifest.json'), JSON.stringify(this.manifest, null, 1) + '\n');
    rmSync(SPECS, { recursive: true, force: true });
    mkdirSync(SPECS, { recursive: true });
    const groups = new Map<string, Spec[]>();
    for (const s of this.specs) {
      const g = s.key.split('.')[0];
      if (!groups.has(g)) groups.set(g, []);
      groups.get(g)!.push(s);
    }
    const index: string[] = [
      '# Art specs',
      '',
      'Generated by `npm run art` from tools/art. Do not edit by hand; edit the generator or replace the PNG.',
      '',
      'How to replace any sprite:',
      '1. Make a PNG with the same size, frame grid and anchor as its spec. Transparent background.',
      '2. Save it over the file in public/assets (path in the spec).',
      '3. Keep the 1 px dark outline (#1e1526) and the palette family so it matches the set.',
      '4. If you change the size or frame count, update the entry in public/assets/manifest.json.',
      '',
      'Scale: 1 art pixel = 2 CSS pixels on a 390-wide phone (integer scaled on every device).',
      '',
    ];
    for (const [g, specs] of groups) {
      index.push(`- [${g}](${g}.md): ${specs.length} assets`);
      const lines: string[] = [`# ${g} assets`, ''];
      for (const s of specs) {
        lines.push(`## ${s.key}`, '', s.desc, '');
        const e = s.entry;
        lines.push(`- File: \`public/assets/${e.file}\``);
        if (e.kind === 'image') {
          lines.push(`- Size: ${e.w} x ${e.h}`);
          if (e.anchor) lines.push(`- Anchor: (${e.anchor.join(', ')})`);
          if (e.slice) lines.push(`- 9-slice insets (L,T,R,B): ${e.slice.join(', ')}; edges and centre tile`);
        } else if (e.kind === 'sheet') {
          lines.push(`- Frame: ${e.frameW} x ${e.frameH}, facing right, one animation per row`);
          lines.push(`- Anchor (feet on ground): (${e.anchor.join(', ')})`);
          if (e.muzzle) lines.push(`- Projectile release point from anchor: (${e.muzzle.join(', ')})`);
          lines.push('- Rows:');
          for (const [n, a] of Object.entries(e.anims)) lines.push(`  - row ${a.row} \`${n}\`: ${a.frames} frames @ ${a.fps} fps${a.loop ? ', loops' : ''}${a.hitFrame !== undefined ? `, hit on frame ${a.hitFrame}` : ''}`);
        } else if (e.kind === 'strip') {
          lines.push(`- Frames: ${e.frames} x (${e.frameW} x ${e.frameH}) in one row @ ${e.fps} fps`, `- Anchor: (${e.anchor.join(', ')})`);
        } else {
          lines.push(`- Cells: ${e.cellW} x ${e.cellH}, glyphs in order: \`${e.glyphs}\``, '- White glyphs; the game tints and outlines them.');
        }
        lines.push(`- Outline: 1 px ${'#1e1526'} where the art has an outline`);
        lines.push(`- Colors (${s.colors.length}): ${s.colors.slice(0, 24).join(' ')}${s.colors.length > 24 ? ' ...' : ''}`, '');
      }
      writeFileSync(join(SPECS, `${g}.md`), lines.join('\n'));
    }
    writeFileSync(join(SPECS, 'README.md'), index.join('\n') + '\n');
  }
}

function portrait(frame: Img, w: number, h: number): Img {
  const b = frame.bounds();
  const cx = Math.round(b.x + b.w / 2) - 1;
  return frame.crop(cx - Math.floor(w / 2), b.y - 2, w, h);
}

export function buildAll(): void {
  rmSync(OUT, { recursive: true, force: true });
  mkdirSync(OUT, { recursive: true });
  const reg = new Registry();

  // Troops
  for (const t of STONE_TROOPS) {
    for (const [teamName, team] of [['blue', TEAM_BLUE], ['red', TEAM_RED]] as const) {
      const r = t.rig(team);
      const anims = t.anims(r);
      const { sheet, rows } = packSheet(anims, r.frameW, r.frameH);
      const anchor: [number, number] = [r.hip[0], r.hip[1] + 4];
      reg.sheet(`troop.${t.id}.${teamName}`, `troops/${t.id}_${teamName}.png`, sheet, r.frameW, r.frameH, anchor, rows, `${t.id} (${teamName} team). Chibi troop, bold outline, lit from the top-left.`, t.muzzle);
      if (teamName === 'blue') reg.image(`portrait.${t.id}`, `portraits/${t.id}.png`, portrait(anims[0].frames[0], 32, 28), `${t.id} card portrait (head and shoulders), fits the card window.`);
    }
  }

  // Environment
  const env = stoneEnv();
  for (const [name, layer] of Object.entries(env.layers)) {
    reg.image(`env.stone.${name}`, `env/stone/${name}.png`, layer.img, `Stone Age battlefield layer "${name}". Row ${layer.groundY} lines up with the ground line.`, { anchor: [0, layer.groundY] });
  }
  env.clouds.forEach((c, i) => reg.image(`env.stone.cloud${i}`, `env/stone/cloud${i}.png`, c, 'Drifting cloud.'));
  reg.manifest.meta['env.stone'] = { skyTop: '#' + (env.skyTop >>> 8).toString(16).padStart(6, '0'), clouds: env.clouds.length, volcanoX: 156, volcanoY: 50 - 128 + 122 };

  // Fortresses
  for (const [teamName, team] of [['blue', TEAM_BLUE], ['red', TEAM_RED]] as const) {
    for (const d of [0, 1, 2, 3] as const) {
      reg.image(`base.stone.${teamName}.${d}`, `bases/stone_${teamName}_${d}.png`, stoneFortress(team, d), `Stone Age fortress, ${teamName} team, damage state ${d} (0 full, 1 damaged, 2 critical, 3 rubble). Faces right; the enemy copy is mirrored in game.`, { anchor: [BASE_FRONT, BASE_GROUND] });
    }
    reg.strip(`fx.flag.${teamName}`, `fx/flag_${teamName}.png`, { frames: flagFrames(team), fps: 8, anchor: [0, 11], desc: `Waving ${teamName} flag, 4 frames; anchor = pole top.` });
  }
  reg.manifest.meta['base.stone'] = { flagX: 26, flagY: 6, torchX: 10, torchY: 49, smokeX: 26, smokeY: 30 };

  // Fonts
  reg.font('font.small', 'ui/font_small.png', smallFont(), 'Small pixel font, caps 5 px. Lowercase renders as caps.');
  reg.font('font.big', 'ui/font_big.png', bigFont(), 'Bold pixel font, caps 7 px, for titles and numbers.');

  // Icons
  for (const [k, img] of Object.entries(icons())) reg.image(`icon.${k}`, `icons/${k}.png`, img, `Icon "${k}".`);

  // UI kit
  const put = (key: string, p: ui.UiPiece) => reg.image(key, `ui/${key.slice(3)}.png`, p.img, p.desc, { ...(p.slice ? { slice: p.slice } : {}), ...(p.anchor ? { anchor: p.anchor } : {}) });
  put('ui.panel', ui.stonePanel());
  put('ui.panel_wood', ui.woodPanel());
  put('ui.inset', ui.insetPanel());
  put('ui.plaque', ui.plaque());
  put('ui.small_plaque', ui.smallPlaque());
  put('ui.btn_green', ui.button(MOSS, false, 'Primary button (green). 9-slice.'));
  put('ui.btn_green_down', ui.button(MOSS, true, 'Primary button pressed.'));
  put('ui.btn_gold', ui.button(GOLD, false, 'Gold button. 9-slice.'));
  put('ui.btn_gold_down', ui.button(GOLD, true, 'Gold button pressed.'));
  put('ui.btn_red', ui.button(TEAM_RED, false, 'Danger button. 9-slice.'));
  put('ui.btn_red_down', ui.button(TEAM_RED, true, 'Danger button pressed.'));
  put('ui.btn_wood', ui.button(WOOD, false, 'Neutral timber button. 9-slice.'));
  put('ui.btn_wood_down', ui.button(WOOD, true, 'Neutral button pressed.'));
  put('ui.btn_grey', ui.button(STONE as never, true, 'Disabled button.'));
  put('ui.card', ui.card(TEAM_BLUE, false));
  put('ui.card_locked', ui.card(TEAM_BLUE, true));
  put('ui.skill_socket', ui.socket(28, false));
  put('ui.hero_socket', ui.socket(38, true));
  put('ui.glow_gold', ui.glowRing(40, GOLD.hl));
  put('ui.glow_blue', ui.glowRing(34, TEAM_BLUE.hl));
  put('ui.tab', ui.tabButton(false));
  put('ui.tab_on', ui.tabButton(true));
  put('ui.tabbar', ui.tabBar());
  put('ui.wall_stone', ui.stoneWall());
  put('ui.ribbon_gold', ui.ribbon(GOLD));
  put('ui.ribbon_grey', ui.ribbon({ hl: STONE.hl, base: STONE.base, shade: STONE.shade, deep: STONE.deep }));

  // Effects
  reg.strip('fx.spark', 'fx/spark.png', fx.spark());
  reg.strip('fx.ring', 'fx/ring.png', fx.ring());
  reg.strip('fx.dust', 'fx/dust.png', fx.dust());
  reg.strip('fx.poof', 'fx/poof.png', fx.poof());
  reg.strip('fx.coin', 'fx/coin.png', fx.coin());
  reg.strip('fx.smoke', 'fx/smoke.png', fx.smoke());
  reg.strip('fx.flame', 'fx/flame.png', fx.flame());
  reg.strip('fx.boom', 'fx/boom.png', fx.boom());
  reg.strip('fx.smear', 'fx/smear.png', fx.smear());
  reg.strip('fx.debris', 'fx/debris.png', fx.debris());
  reg.strip('proj.stone', 'fx/proj_stone.png', fx.stoneProjectile());

  reg.writeAll();
  void INK;
  console.log(`Built ${Object.keys(reg.manifest.assets).length} assets into public/assets`);
}

buildAll();
