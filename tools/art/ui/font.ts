export interface FontAtlas {
  img: Img;
  glyphs: string;
  widths: number[];
  cellW: number;
  cellH: number;
}

function build(table: Record<string, string[]>, cellH: number): FontAtlas {
  const glyphs = Object.keys(table).join('');
  const cellW = Math.max(...Object.values(table).map((g) => g[0].length));
  const img = new Img(cellW * glyphs.length, cellH);
  const widths: number[] = [];
  [...glyphs].forEach((ch, i) => {
    const rows = table[ch];
    widths.push(rows[0].length);
    rows.forEach((row, y) => {
      for (let x = 0; x < row.length; x++) if (row[x] === '#') img.set(i * cellW + x, y, 0xffffffff);
    });
  });
  return { img, glyphs, widths, cellW, cellH };
}

export const smallFont = () => build(SMALL, 6);
export const bigFont = () => build(BIG, 8);
