export function icons(): Record<string, Img> {
  const out: Record<string, Img> = {};
  for (const [k, rows] of Object.entries(ICONS)) out[k] = Img.fromGrid(rows, PAL).outlined(INK);
  for (const [k, rows] of Object.entries(TAB_ICONS)) out['tab_' + k] = Img.fromGrid(rows, PAL).outlined(INK);
  void FIRE;
  return out;
}
